# the script runs on an embedded copy of its source through the system bash: exact semantics, no native speedup
compile_fallback() {   # src srcname -> R = module
	local esc
	irbytes "$1"
	esc=$R
	R="; generated by bashful from $2 (bash fallback)"$'\n'"source_filename = \"$2\""$'\n\n'
	R+="@script = private unnamed_addr constant [$((${#1} + 1)) x i8] c\"$esc\\00\", align 1"$'\n'
	R+="@bash_rt_embed = constant i32 $((!NO_EMBED))"$'\n'
	R+="declare i32 @bash_rt_fallback(i32, ptr, ptr)"$'\n\n'"define i32 @main(i32 %argc, ptr %argv) {"$'\n'
	R+="  %r = call i32 @bash_rt_fallback(i32 %argc, ptr %argv, ptr @script)"$'\n'"  ret i32 %r"$'\n'"}"$'\n'
}
# native compilation of SRC into the file $2; exit status 3 (with UNSUP in $3) when the script needs the fallback.
# Runs in a subshell: a parse error deep inside the parser simply exits.
compile_native() {   # srcname out_file unsup_file
	local root k i nk line t num last nm hdr
	local -a rk
	UNSUP_FILE=$3
	ARMED=1
	S=$SRC I=0 PEND= LINEBASE=0 NOREBASE=0
	parse_list
	root=$R
	skip_ws 1
	[[ -n ${S:I:1} ]] && perr "unexpected token"
	NOREBASE=1
	walk $root
	shlib_nodes
	NK[root]="$R${NK[root]}"
	ARMED=0
	rk=(${NK[root]})
	for k in "${rk[@]}"; do   # functions defined exactly once, at the top level: called directly once defined
		if ((NT[k] == N_FUNC && FNB_COUNT[_${NNAME[k]}] == 1)); then
			DNODEIX[k]=$ND
			DIRECTIX[_${NNAME[k]}]=$ND
			((ND++))
		fi
	done
	if [[ -n $UNSUP ]]; then printf '%s' "$UNSUP" > "$3"; exit 3; fi
	FB= FA= FT=0 FRET=Lret FCOND=0 LOOPBASE=0 COLD_OK=1 HOT=0
	emit "call void @bash_rt_init(i32 %argc, ptr %argv, ptr @bash_names, i32 NNAMES__)"
	if ((CMD_MODE)); then gen_node $root
	else   # script: each source line runs under bash_rt_line, which an expansion error (bad $((...))) abandons
		nk=${#rk[@]}
		i=0
		while ((i < nk)); do
			mk $N_LIST
			line=$R
			while :; do
				NK[line]+=" ${rk[i]}"
				((i++))
				((NEOL[rk[i - 1]] == 0 && i < nk)) || break
			done
			gen_block_fn $line
			t=$((TMP++))
			emit "%t$t = call i32 @bash_rt_line(ptr $R)"
		done
		((nk)) || set_status_const 0
	fi
	br Lret
	label Lret
	t=$((TMP++))
	emit "%t$t = call i32 @bash_rt_get_status()"
	emit "call void @bash_rt_exit(i32 %t$t)"
	emit_term "ret i32 %t$t"
	fn_flush "define i32 @main(i32 %argc, ptr %argv) "
	COLD_OK=0
	printf -v num '%-8d' $NVN
	last=$((${#FUNCS[@]} - 1))
	FUNCS[last]=${FUNCS[last]/NNAMES__/$num}
	hdr="; generated by bashful from $1"$'\n'"source_filename = \"$1\""$'\n\n'"$DECLS@bash_rt_embed = constant i32 $((!NO_EMBED))"$'\n'
	for ((i = 0; i < NTOOLS; i++)); do ((USED[i])) && hdr+="declare i32 @${TOOL_PFX[i]}${TOOL_ID[i]}(i32, ptr)"$'\n'; done
	hdr+=$'\n'
	if ((NVN)); then nm="@bash_names = private constant [$NVN x ptr] ["; else nm="@bash_names = private constant [1 x ptr] ["; fi
	for ((i = 0; i < NVN; i++)); do
		S "${VN[i]}"
		((i)) && nm+=", "
		nm+="ptr $R"
	done
	((NVN)) || nm+="ptr null"
	nm+="]"$'\n'
	{
		printf '%s' "$hdr"
		((${#STRS[@]})) && printf '%s\n' "${STRS[@]}"
		printf '\n%s' "$nm"
		for ((i = 0; i < ND; i++)); do printf '@bash_ufd_%d = internal global i1 false\n' $i; done
		printf '%s' "${FUNCS[@]}"
	} > "$2"
	exit 0
}
